"""Generate the mID -> machine name table from a decompiled MetaTileEntityIDs enum.

The enum in GT5-Unofficial looks like::

    public enum MetaTileEntityIDs {
       HULL_BRONZE(1),
       HULL_BRICKED_BRONZE(2),
       ...
       EyeofHarmony(15410),
    }

Decompile ``gregtech/api/enums/MetaTileEntityIDs.class`` from the GT5U jar (e.g. with
JetBrains FernFlower / IntelliJ), then run::

    python scripts/gen_mte_ids.py --source MetaTileEntityIDs.java \
        --out gtnh_save_inspector/data/mte_ids.py

The generated table is for the GT version the jar came from; different pack versions may
have different ids, so regenerate when updating.
"""

from __future__ import annotations

import argparse
import re

PATTERN = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*\(\s*(-?\d+)\s*\)\s*,?\s*$")


def parse_enum(path: str):
    mapping = {}
    duplicates = []
    with open(path, encoding="utf-8", errors="replace") as handle:
        for line in handle:
            match = PATTERN.match(line)
            if not match:
                continue
            name, number = match.group(1), int(match.group(2))
            if number in mapping and mapping[number] != name:
                duplicates.append((number, mapping[number], name))
                continue
            mapping[number] = name
    return mapping, duplicates


def render(mapping) -> str:
    lines = [
        '"""mID -> GT machine registration name (generated by scripts/gen_mte_ids.py).',
        "",
        "Generated from gregtech/api/enums/MetaTileEntityIDs of the GT5-Unofficial jar in use.",
        '"""',
        "",
        "MTE_NAMES = {",
    ]
    for number in sorted(mapping):
        lines.append("    %d: %r," % (number, mapping[number]))
    lines.append("}")
    lines.append("")
    lines.append("")
    lines.append("def mte_name(mte_id):")
    lines.append('    """Return the registration name for a meta tile entity id, or None."""')
    lines.append("    if not isinstance(mte_id, int):")
    lines.append("        return None")
    lines.append("    return MTE_NAMES.get(mte_id)")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, help="decompiled MetaTileEntityIDs.java")
    parser.add_argument("--out", required=True, help="output python file")
    args = parser.parse_args()
    mapping, duplicates = parse_enum(args.source)
    if not mapping:
        raise SystemExit("no enum entries found in %s" % args.source)
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(render(mapping))
    print("wrote %d ids to %s" % (len(mapping), args.out))
    if duplicates:
        print("skipped %d duplicate ids: %r" % (len(duplicates), duplicates[:5]))


if __name__ == "__main__":
    main()
